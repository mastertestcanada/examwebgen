// MasterTest Web in English and French. The page is written in English; I18N.fr gives the French
// for each English text, the page's own (translated when the language changes, by
// translatePage) and the texts wizard.js builds (through tr and trn). {name} marks a value filled
// in. A text missing from the list stays in English. The messages of MasterTest Builder itself
// (the errors and warnings it prints) are in English.
"use strict";

const UI_LANGS = { en: "English", fr: "Français" };
let uiLang = (() => {
  try { const saved = localStorage.getItem("mastertest-ui-lang"); if (saved && UI_LANGS[saved]) return saved; } catch (e) { /* no storage */ }
  return (navigator.language || "en").toLowerCase().startsWith("fr") ? "fr" : "en";
})();

// French typography: a non-breaking space before : ; ? ! and inside « », so lines never break there
const frenchSpaces = (t) => t.replace(/ ([:;?!»])/g, " $1").replace(/« /g, "« ");

function tr(en, vars) {
  let s = en;
  if (uiLang !== "en") {
    const t = I18N[uiLang] && I18N[uiLang][en];
    if (t !== undefined) s = uiLang === "fr" ? frenchSpaces(t) : t;
  }
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

// one or many: English uses the singular for 1, French for 0 and 1
function trn(n, one, many, vars) {
  const single = uiLang === "fr" ? Math.abs(n) < 2 : n === 1;
  return tr(single ? one : many, { n, ...(vars || {}) });
}

// The page's own text and the attributes people read, translated in place. The English is kept
// so the page can switch back; text the code has changed since is left to the code.
const ORIGINAL = new WeakMap();
const ATTRS = ["placeholder", "aria-label", "title", "alt", "label"];
function translatePage(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => (n.parentElement && n.parentElement.closest("script, style, svg, [data-no-tr]") ? NodeFilter.FILTER_REJECT
      : /[A-Za-z]/.test(n.nodeValue) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT),
  });
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    let o = ORIGINAL.get(n);
    if (!o) { o = { en: n.nodeValue, last: n.nodeValue }; ORIGINAL.set(n, o); }
    else if (n.nodeValue !== o.last) { o.en = n.nodeValue; }        // changed by the code: that is its English now
    const key = o.en.replace(/\s+/g, " ").trim();
    const lead = o.en.match(/^\s*/)[0], tail = o.en.match(/\s*$/)[0];
    n.nodeValue = lead + tr(key) + tail;
    o.last = n.nodeValue;
  }
  for (const el of root.querySelectorAll(ATTRS.map((a) => `[${a}]`).join(","))) {
    if (el.closest("[data-no-tr]")) continue;
    for (const a of ATTRS) {
      if (!el.hasAttribute(a)) continue;
      const key = "attr:" + a;
      if (!el.dataset[key.replace(":", "_").replace("-", "_")]) el.dataset[key.replace(":", "_").replace("-", "_")] = el.getAttribute(a);
      el.setAttribute(a, tr(el.dataset[key.replace(":", "_").replace("-", "_")]));
    }
  }
  document.documentElement.lang = uiLang;
}

